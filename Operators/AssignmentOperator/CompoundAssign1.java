class CompoundAssign1{
  public static void main(String[] args){
    System.out.println("Welcome to Compound Assignment Operator!");
    double a = 23.5;
    double b = 22.3;
    a += b;  // a = a+b;
    System.out.println(a);
    System.out.println("================");
    int x = 20;
    int y = 30;
    x += y; // x = x+y;
    System.out.println(x);
    System.out.println("=================");
    int e = 10;
    int f = 20;
    e -= f; // e = e+f;
    System.out.println(e);
    System.out.println("=================");
    int c = 10;
    int d = 60;
    c *= d; //c = c*d;
    System.out.println(c);
    System.out.println("==================");
    
    
  }
}