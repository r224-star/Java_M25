class Widening{
  public static void main(String[] args){
    int a = 25;
    double b = (double)a;
    System.out.println(b);
    System.out.println("===============");
    char c = 90;
    int d = (int)c;
    System.out.println(d);
    System.out.println("===============");
    float f = 48.369f;
    double j = (double)f;
    System.out.println(j);
    System.out.println("===============");
    int x = 68;
    double y = (double)x;
    System.out.println(y);
    System.out.println("===============");
  }
}